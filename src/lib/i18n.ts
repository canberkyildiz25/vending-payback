export const LOCALE: Record<Lang, string> = { en: "en-US", tr: "tr-TR", nl: "nl-NL" };

const isLang = (v: string | null | undefined): v is Lang => !!v && (LANGS as readonly string[]).includes(v);

/**
 * Chosen language first, then the visitor's country (Vercel sets
 * x-vercel-ip-country from the IP), then the browser's language, then English.
 */
export function pickLang(opts: { cookie?: string | null; country?: string | null; acceptLanguage?: string | null }): Lang {
  if (isLang(opts.cookie)) return opts.cookie;
  const c = opts.country?.toUpperCase();
  if (c === "TR" || c === "CY") return "tr";
  if (c === "NL" || c === "BE" || c === "SR") return "nl";
  const first = opts.acceptLanguage?.split(",")[0]?.trim().slice(0, 2).toLowerCase();
  if (isLang(first)) return first;
  return "en";
}

